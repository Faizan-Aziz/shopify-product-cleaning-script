"""
Pydantic models for structured data throughout the pipeline.

* ``ProductDescription`` – normalised description fields.
* ``SEOData``            – SEO title / meta / tags returned by the LLM.
* ``LLMResponse``        – top-level schema the LLM must conform to
                           (used with OpenAI Structured Outputs).
* ``MetafieldEntry``     – a single Shopify metafield payload item.
"""

from __future__ import annotations

from typing import Optional

from pydantic import BaseModel, Field


# ── Description table ────────────────────────────────────────────────────

class ProductDescription(BaseModel):
    """Normalised product description fields extracted from Shopify HTML."""

    product_name: Optional[str] = Field(None, alias="Product Name")
    product_type: Optional[str] = Field(None, alias="Product Type")
    brand: Optional[str] = Field(None, alias="Brand")
    part_number: Optional[str] = Field(None, alias="Part Number")
    removed_from: Optional[str] = Field(None, alias="Removed From")
    condition: Optional[str] = Field(None, alias="Condition")
    condition_grade: Optional[str] = Field(None, alias="Condition Grade")
    color: Optional[str] = Field(None, alias="Color")
    material: Optional[str] = Field(None, alias="Material")
    fitment: Optional[str] = Field(None, alias="Fitment")
    description: Optional[str] = Field(None, alias="Description")
    features: Optional[str] = Field(None, alias="Features")
    condition_notes: Optional[str] = Field(None, alias="Condition Notes")

    model_config = {"populate_by_name": True}


# ── SEO payload ──────────────────────────────────────────────────────────

class SEOData(BaseModel):
    """SEO metadata generated by the LLM."""

    title: Optional[str] = None
    meta_description: Optional[str] = None
    product_type: Optional[str] = None
    tags: list[str] = Field(default_factory=list)


# ── Metafields returned by the LLM ──────────────────────────────────────

class LLMMetafields(BaseModel):
    """Metafield values the LLM may fill in as a fallback."""

    spec_material: Optional[str] = Field(None, alias="custom.spec_material")
    spec_color: Optional[str] = Field(None, alias="custom.spec_color")
    condition_notes: Optional[str] = Field(None, alias="custom.condition_notes")
    condition_grade: Optional[str] = Field(None, alias="custom.condition_grade")
    condition_status: Optional[str] = Field(None, alias="custom.condition_status")
    manufacturer_type: Optional[str] = Field(None, alias="custom.manufacturer_type")
    manufacturer_name: Optional[str] = Field(None, alias="custom.manufacturer_name")
    part_part_number: Optional[str] = Field(None, alias="custom.part_part_number")
    part_part_type: Optional[str] = Field(None, alias="custom.part_part_type")
    part_sub_category: Optional[str] = Field(None, alias="custom.part_sub_category")
    part_category: Optional[str] = Field(None, alias="custom.part_category")
    vehicle_removed_from_year: Optional[str] = Field(
        None, alias="custom.vehicle_removed_from_year"
    )
    vehicle_year_from: Optional[str] = Field(None, alias="custom.vehicle_year_from")
    vehicle_year_to: Optional[str] = Field(None, alias="custom.vehicle_year_to")
    vehicle_make: Optional[str] = Field(None, alias="custom.vehicle_make")
    vehicle_model: Optional[str] = Field(None, alias="custom.vehicle_model")

    model_config = {"populate_by_name": True}


# ── Combined LLM response ───────────────────────────────────────────────

class LLMResponse(BaseModel):
    """
    Top-level schema for the OpenAI Structured Outputs response.

    The LLM is expected to return JSON matching this exact shape.
    """

    seo: SEOData = Field(default_factory=SEOData)
    description: ProductDescription = Field(default_factory=ProductDescription)
    metafields: LLMMetafields = Field(default_factory=LLMMetafields)


# ── Shopify metafield input ─────────────────────────────────────────────

class MetafieldEntry(BaseModel):
    """A single metafield payload item for the Shopify ``metafieldsSet`` mutation."""

    ownerId: str
    namespace: str
    key: str
    type: str
    value: str
